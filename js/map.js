const ROWS = MAP.length;
const COLS = MAP[0].length;

// Returns true if the given world position is inside a wall
function isWall(x,y){
    let mx = Math.floor(x);
    let my = Math.floor(y);
    if (mx < 0 || my < 0 || mx >= COLS || my >= ROWS) return true;
    return MAP[my][mx] === 1;
}